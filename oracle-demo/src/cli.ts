// Demo commands (chipnet only). Run from the repository root:
//
//   npm run demo:keys -- --write              create demo keys in .env (never committed)
//   npm run demo:deploy                       deploy Paryon's add-collateral contracts + demo loans
//   npm run demo:setup -- --reserve 0.5       move demo loan 0's key and a reserve into a vault
//   npm run demo:status                       show every vault in keeper/vaults.json
//   npm run demo:crash -- --price 250         publish a DEMO oracle price
//   npm run demo:withdraw                     the borrower takes everything back
//   npm run demo:links                        Markdown table of the demo's transactions, for docs
//
// All amounts are BCH; prices are US dollars per BCH.
import { parseArgs } from 'node:util';
import { resolve } from 'node:path';
import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { ElectrumNetworkProvider, Network, type NetworkProvider } from 'cashscript';
import { binToHex, cashAddressToLockingBytecode, decodeTransaction, hexToBin } from '@bitauth/libauth';
import type { VaultList } from '@backstop/keeper';
import { deploymentContracts, history, loadVault, vaultHistory } from '@backstop/contracts';
import { deployDemo, type DemoDeployment } from './deploy.js';
import { publishDemoPrice } from './price.js';
import { setUpDemoVault, vaultStatus, withdrawDemoVault } from './borrower.js';
import { newWallet, walletFromEnv } from './wallet.js';

const root = resolve(import.meta.dirname, '../..');
const envFile = resolve(root, '.env');
const deploymentFile = resolve(root, 'deployments/chipnet.json');
const vaultsFile = resolve(root, 'keeper/vaults.json');
if (existsSync(envFile)) process.loadEnvFile(envFile);

const explorer = (txid: string) => `https://chipnet.imaginary.cash/tx/${txid}`;
const bchToSats = (bch: string) => {
  const [whole, frac = ''] = bch.split('.');
  if (!/^\d+$/.test(whole) || !/^\d{0,8}$/.test(frac)) throw new Error(`not a BCH amount: ${bch}`);
  return BigInt(whole) * 100_000_000n + BigInt(frac.padEnd(8, '0'));
};
const usdToCents = (usd: string) => BigInt(Math.round(Number(usd) * 100));
const percentToBps = (pct: string) => BigInt(Math.round(Number(pct) * 100));
const fmtUsd = (cents: bigint) => `$${(Number(cents) / 100).toFixed(2)}`;
const fmtBch = (sats: bigint) => `${(Number(sats) / 1e8).toFixed(8)} BCH`;
const fmtPct = (bps: bigint) => `${(Number(bps) / 100).toFixed(1)}%`;

const [command, ...rest] = process.argv.slice(2);
const { values } = parseArgs({
  args: rest,
  options: {
    write: { type: 'boolean', default: false },
    force: { type: 'boolean', default: false },
    server: { type: 'string' },
    price: { type: 'string' },
    loans: { type: 'string', default: '2' },
    collateral: { type: 'string', default: '0.5' },
    debt: { type: 'string', default: '115' },
    'borrower-address': { type: 'string' },
    loan: { type: 'string', default: '0' },
    reserve: { type: 'string', default: '0.5' },
    'max-topup': { type: 'string' },
    trigger: { type: 'string', default: '125' },
    target: { type: 'string', default: '150' },
    cooldown: { type: 'string', default: '1' },
    vault: { type: 'string' },
  },
});

async function connect(): Promise<NetworkProvider> {
  const provider = new ElectrumNetworkProvider(Network.CHIPNET, values.server ? { hostname: values.server } : {});
  try {
    await provider.getBlockHeight();
  } catch (error) {
    throw new Error(`Cannot reach a chipnet Electrum server (${(error as Error).message}). Try --server chipnet.imaginary.cash`);
  }
  return provider;
}

const readDeployment = (): DemoDeployment => {
  if (!existsSync(deploymentFile)) throw new Error('No deployments/chipnet.json yet. Run "npm run demo:deploy" first.');
  return JSON.parse(readFileSync(deploymentFile, 'utf8')) as DemoDeployment;
};
const readVaults = (): VaultList => (existsSync(vaultsFile) ? JSON.parse(readFileSync(vaultsFile, 'utf8')) : { vaults: [] });

async function main() {
  switch (command) {
    case 'keys': {
      const lines = [
        '',
        '# --- DEMO keys (chipnet only, generated by npm run demo:keys) ---',
        '# Demo oracle: signs demo prices. Mainnet would use General Protocols\' oracle instead.',
        `DEMO_ORACLE_WIF=${newWallet().wif}`,
        '# Funder: pays for the demo deployment and price updates. Fund it from https://chipnet.bch.ninja/',
        `DEMO_FUNDER_WIF=${newWallet().wif}`,
        '# Demo borrower: holds the demo loan key for the scripted setup. Fund it too.',
        `DEMO_BORROWER_WIF=${newWallet().wif}`,
      ];
      if (!values.write) {
        console.log('Add these lines to .env (or rerun with --write):');
        console.log(lines.join('\n'));
        return;
      }
      if (existsSync(envFile) && /DEMO_(ORACLE|FUNDER|BORROWER)_WIF=/.test(readFileSync(envFile, 'utf8'))) {
        throw new Error('.env already has demo keys; not overwriting them');
      }
      appendFileSync(envFile, lines.join('\n') + '\n');
      process.loadEnvFile(envFile);
      const funder = walletFromEnv('DEMO_FUNDER_WIF');
      const borrower = walletFromEnv('DEMO_BORROWER_WIF');
      console.log('Demo keys written to .env (git ignores it).');
      console.log(`Fund the funder with ~1.2 tBCH:   ${funder.address}`);
      console.log(`Fund the borrower with ~0.6 tBCH: ${borrower.address}`);
      console.log('Faucet: https://chipnet.bch.ninja/');
      return;
    }

    case 'deploy': {
      if (existsSync(deploymentFile) && !values.force) throw new Error('deployments/chipnet.json exists. Use --force to make a new deployment (the old one stays on chain).');
      const provider = await connect();
      const funder = walletFromEnv('DEMO_FUNDER_WIF');
      const oracle = walletFromEnv('DEMO_ORACLE_WIF');
      let borrowerLockingBytecode: string;
      if (values['borrower-address']) {
        const decoded = cashAddressToLockingBytecode(values['borrower-address']);
        if (typeof decoded === 'string') throw new Error(`--borrower-address: ${decoded}`);
        borrowerLockingBytecode = binToHex(decoded.bytecode);
      } else {
        borrowerLockingBytecode = walletFromEnv('DEMO_BORROWER_WIF').lockingBytecode;
      }
      const startPriceCents = usdToCents(values.price ?? '300');
      const loans = Array.from({ length: Number(values.loans) }, () => ({
        collateralSats: bchToSats(values.collateral), debtCents: usdToCents(values.debt), borrowerLockingBytecode,
      }));
      const deployment = await deployDemo({ provider, funder, oracle, startPriceCents, loans });
      writeFileSync(deploymentFile, JSON.stringify(deployment, null, 2) + '\n');
      console.log(`\nDeployed. Written to deployments/chipnet.json`);
      console.log(`Genesis: ${explorer(deployment.demo.genesisTxid)}`);
      deployment.demo.loans.forEach((l, i) => console.log(`Demo loan ${i}: ${fmtBch(BigInt(l.collateralSats))} collateral, ${fmtUsd(BigInt(l.debtCents))} debt, loan key ${l.loanKeyCategory}`));
      return;
    }

    case 'setup': {
      const provider = await connect();
      const deployment = readDeployment();
      const loan = deployment.demo.loans[Number(values.loan)];
      if (!loan) throw new Error(`no demo loan ${values.loan}`);
      const reserveSats = bchToSats(values.reserve);
      const result = await setUpDemoVault({
        provider, deployment, borrower: walletFromEnv('DEMO_BORROWER_WIF'), loanKeyCategory: loan.loanKeyCategory, reserveSats,
        maxTopUpSats: values['max-topup'] ? bchToSats(values['max-topup']) : undefined,
        triggerRatioBps: percentToBps(values.trigger), targetRatioBps: percentToBps(values.target), cooldownBlocks: BigInt(values.cooldown),
      });
      const list = readVaults();
      list.vaults.push({ setupTxid: result.setupTxid, note: `demo loan ${values.loan}` });
      writeFileSync(vaultsFile, JSON.stringify(list, null, 2) + '\n');
      console.log(`Vault ${result.address} set up: ${explorer(result.setupTxid)}`);
      console.log('Added to keeper/vaults.json.');
      return;
    }

    case 'status': {
      const provider = await connect();
      const deployment = readDeployment();
      for (const { setupTxid, note } of readVaults().vaults) {
        const s = await vaultStatus({ provider, deployment, setupTxid });
        console.log(`\n${note ?? setupTxid}  ${s.address}`);
        if ('empty' in s) { console.log(`  ${s.empty}`); continue; }
        console.log(`  price ${fmtUsd(s.priceCents)} (DEMO oracle) | debt ${fmtUsd(s.debtCents)} | collateral ${fmtBch(s.collateralSats)} | ratio ${fmtPct(s.ratioBps)}`);
        console.log(`  rescue below ${fmtUsd(s.triggerPriceCents)} | liquidation below ${fmtUsd(s.liquidationPriceCents)} | reserve ${fmtBch(s.reserveSats)}`);
      }
      return;
    }

    case 'crash': {
      if (!values.price) throw new Error('usage: npm run demo:crash -- --price 250');
      const provider = await connect();
      const results = await publishDemoPrice({
        provider, deployment: readDeployment(), oracle: walletFromEnv('DEMO_ORACLE_WIF'), funder: walletFromEnv('DEMO_FUNDER_WIF'),
        priceCents: usdToCents(values.price), log: () => {},
      });
      for (const r of results) console.log(`DEMO oracle price ${fmtUsd(r.fromCents)} -> ${fmtUsd(r.toCents)}: ${explorer(r.txid)}`);
      return;
    }

    case 'withdraw': {
      const provider = await connect();
      const vaults = readVaults().vaults;
      const setupTxid = values.vault ?? vaults.at(-1)?.setupTxid;
      if (!setupTxid) throw new Error('no vault to withdraw from');
      const txid = await withdrawDemoVault({ provider, borrower: walletFromEnv('DEMO_BORROWER_WIF'), setupTxid });
      console.log(`Withdrawn: ${explorer(txid)}`);
      return;
    }

    case 'links': {
      const provider = await connect();
      const deployment = readDeployment();
      const rows = [
        '| Transaction | What it does | Explorer |',
        '|---|---|---|',
        `| Demo deployment | Paryon's price contract, manage function, demo loans and loan keys | [${deployment.demo.genesisTxid.slice(0, 12)}…](${explorer(deployment.demo.genesisTxid)}) |`,
      ];
      const paryon = deploymentContracts(provider, deployment);
      for (const { txid } of await history(provider, paryon.price.lockingBytecode)) {
        if (txid === deployment.demo.genesisTxid) continue;
        // Rescues also spend the price contract (to read it); list those under their vault instead.
        const tx = decodeTransaction(hexToBin(await provider.getRawTransaction(txid)));
        if (typeof tx !== 'string' && tx.inputs.length === 2) rows.push(`| Price update | DEMO oracle price into Paryon's price contract | [${txid.slice(0, 12)}…](${explorer(txid)}) |`);
      }
      for (const { setupTxid, note } of readVaults().vaults) {
        const vault = await loadVault(provider, setupTxid);
        for (const event of await vaultHistory(provider, vault)) {
          const what = event.kind === 'setup' ? `Setup${note ? ` (${note})` : ''}: key and ${fmtBch(event.reserveSats)} reserve into the vault`
            : event.kind === 'rescue' ? `Rescue: ${fmtBch(event.topUpSats)} into the loan, ${event.overheadSats} sats fee + reward`
            : 'Withdraw: key and reserve back to the borrower';
          rows.push(`| ${event.kind[0].toUpperCase()}${event.kind.slice(1)} | ${what} | [${event.txid.slice(0, 12)}…](${explorer(event.txid)}) |`);
        }
      }
      console.log(rows.join('\n'));
      return;
    }

    default:
      console.log('commands: keys, deploy, setup, status, crash, withdraw, links (see oracle-demo/src/cli.ts)');
  }
}

main().then(() => process.exit(0), (error) => {
  console.error((error as Error).message);
  process.exit(1);
});
