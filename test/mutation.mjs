// Mutation test for Backstop.cash: delete each `require`, one at a time, and check that some test fails.
//
//   node test/mutation.mjs            (from the repository root; takes about half an hour)
//
// For every require it recompiles the contract without that line and runs the behaviour tests,
// stopping at the first failure. It records which test caught the deletion, or that none did, and
// writes docs/MUTATION.md. The original contract is restored at the end, even on error.
// test/xo.test.ts is left out: it compares the XO template with the compiled bytecode, so it would
// fail for every change and prove nothing about behaviour.
import { execFileSync, spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const contract = join(root, 'contracts', 'Backstop.cash');
const original = readFileSync(contract, 'utf8');
const lines = original.split('\n');
const behaviourTests = ['rescue', 'owner', 'setup', 'node', 'story', 'keeper', 'demo', 'lookups', 'price', 'wizardconnect']
  .map((name) => `${name}.test.ts`);

const compile = () => spawnSync('node', [join(root, 'contracts', 'scripts', 'compile.mjs')], { encoding: 'utf8' });
const functionAt = (index) => {
  for (let i = index; i >= 0; i--) {
    const m = lines[i].match(/function (\w+)\(/);
    if (m) return m[1];
  }
  return '?';
};

const results = [];
const scratch = mkdtempSync(join(tmpdir(), 'backstop-mutation-'));
try {
  const targets = lines.map((line, i) => ({ line, i })).filter(({ line }) => /^\s*require\(/.test(line));
  for (const [n, { line, i }] of targets.entries()) {
    const message = line.match(/"([^"]+)"\);\s*$/)?.[1] ?? line.trim();
    const mutated = [...lines];
    mutated[i] = line.replace(/require\(.*$/, '// (removed by mutation test)');
    writeFileSync(contract, mutated.join('\n'));
    const built = compile();
    let result;
    if (built.status !== 0) {
      result = { outcome: 'compiler', detail: (built.stderr || built.stdout).split('\n').find((l) => l.trim()) ?? 'compile error' };
    } else {
      const report = join(scratch, `${n}.json`);
      spawnSync('npx', ['vitest', 'run', '--bail=1', '--reporter=json', `--outputFile=${report}`, ...behaviourTests],
        { cwd: join(root, 'test'), encoding: 'utf8', timeout: 15 * 60 * 1000 });
      let failed;
      try {
        const json = JSON.parse(readFileSync(report, 'utf8'));
        for (const file of json.testResults ?? []) {
          for (const test of file.assertionResults ?? []) {
            if (test.status === 'failed' && !failed) failed = { name: test.fullName ?? test.title, file: file.name.split('/').pop() };
          }
        }
      } catch {
        failed = { name: 'test run did not complete', file: '' };
      }
      result = failed ? { outcome: 'caught', detail: `${failed.file}: ${failed.name}` } : { outcome: 'survived', detail: 'no test failed' };
    }
    results.push({ line: i + 1, fn: functionAt(i), message, ...result });
    console.log(`${String(n + 1).padStart(2)}/${targets.length} line ${i + 1} ${result.outcome}: ${result.detail}`);
  }
} finally {
  writeFileSync(contract, original);
  compile();
  rmSync(scratch, { recursive: true, force: true });
}

const count = (o) => results.filter((r) => r.outcome === o).length;
const escape = (s) => s.replace(/\|/g, '\\|');
const date = new Date().toISOString().slice(0, 10);
const commit = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
writeFileSync(join(root, 'docs', 'MUTATION.md'), `# Mutation test: every \`require\` matters

Generated by \`node test/mutation.mjs\` on ${date} at commit \`${commit}\`. Do not edit by hand.

Each \`require\` in \`contracts/Backstop.cash\` was deleted, one at a time; the contract was recompiled and the
behaviour tests were run (${behaviourTests.join(', ')}). A deletion is **caught** when at least one test then fails.

**${count('caught')} of ${results.length} caught**${count('survived') ? `, **${count('survived')} survived**` : ''}${count('compiler') ? `, ${count('compiler')} rejected by the compiler` : ''}.

| Line | Function | require message | Result | First failing test |
|---|---|---|---|---|
${results.map((r) => `| ${r.line} | ${r.fn} | ${escape(r.message)} | ${r.outcome} | ${escape(r.detail)} |`).join('\n')}
`);
console.log(`\n${count('caught')}/${results.length} caught, ${count('survived')} survived, ${count('compiler')} compiler. Wrote docs/MUTATION.md`);
